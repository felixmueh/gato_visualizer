def _flag(values: Mapping[str, Any], key: str) -> bool:
    if not isinstance(values[key], bool):
        raise ValueError(f"{key} must be a boolean")
    return values[key]


def build_simulation(values: Mapping[str, Any], base):
    """The plant with or without the supplied armature (its friction stays the base's) and
    the execution law, None for the package loop's default; inactive choices are validated too."""
    import tiago_mpc as tm
    armature = tm.ARMATURE_KG_M2 if _flag(values, "armature_on") else (0.,) * 7
    evaluation = tm.Tanh(values["ff_width_rad_s"])
    mode = values["law"]
    if mode not in dict(LAWS):
        raise ValueError(f"Unknown execution law: {mode!r}")
    if mode == "default":
        return replace(base, armature=armature), None  # the package loop's default law
    law = tm.PlanFeedback() if mode in ("pd", "both") else tm.SampleKnot()
    if mode in ("ff", "both"):
        law = tm.FrictionFeedforward(tm.urdf_friction(), law, evaluation=evaluation)
    return replace(base, armature=armature), law


def build_predictor(values: Mapping[str, Any], base):
    """The predictor's armature, friction (URDF coefficients, tanh width) and collision rows;
    rho stays the base's (Collision's default when the base has no rows). Model changes may
    need another compiled module; only the visualizer's explicit Build compiles it."""
    import tiago_mpc as tm
    from tiago_mpc.collision import Collision
    armature = tm.ARMATURE_KG_M2 if _flag(values, "armature_on") else (0.,) * 7
    base = replace(base, armature=armature, friction=tm.urdf_friction() if _flag(values, "friction_on") else None,
                   friction_law=tm.Tanh(values["friction_width_rad_s"]))
    if not _flag(values, "enabled"):
        return replace(base, collision=None)
    arm, body = values["arm"], values["body"]
    if arm not in {choice["value"] for choice in cover_choices("arm")}:
        raise ValueError(f"Unknown arm cover: {arm!r}")
    if body not in {choice["value"] for choice in cover_choices("body")}:
        raise ValueError(f"Unknown body cover: {body!r}")
    shapes = {path: tuple(tuple(map(float, item)) for item in values[path]) for path, *_ in SHAPES}
    return replace(base, collision=replace(base.collision or Collision(), arm=arm, body=body,
                                           margin_m=float(values["margin_m"]), mechanism=values["mechanism"], **shapes))
